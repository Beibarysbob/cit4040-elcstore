-- PostgreSQL 15; idempotent bootstrap for a fresh shopdb
-- Migrations are applied on first docker volume initialization.
CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    phone VARCHAR(255),
    role VARCHAR(40) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    last_login_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    country VARCHAR(255) NOT NULL,
    city VARCHAR(255) NOT NULL,
    street VARCHAR(255) NOT NULL,
    building VARCHAR(255) NOT NULL,
    apartment VARCHAR(255),
    postal_code VARCHAR(255),
    recipient_name VARCHAR(255) NOT NULL,
    recipient_phone VARCHAR(255) NOT NULL,
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    latitude NUMERIC(14,2),
    longitude NUMERIC(14,2),
    user_id BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS brands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,
    logo_url VARCHAR(255),
    website_url VARCHAR(255),
    country VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,
    image_url VARCHAR(255),
    sort_order INTEGER NOT NULL DEFAULT 0,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    parent_category_id BIGINT
);
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    slug VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,
    short_description TEXT,
    sku VARCHAR(255) NOT NULL UNIQUE,
    base_price NUMERIC(14,2) NOT NULL,
    discount_price NUMERIC(14,2),
    discount_start_date TIMESTAMP,
    discount_end_date TIMESTAMP,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    reserved_quantity INTEGER NOT NULL DEFAULT 0,
    low_stock_threshold INTEGER NOT NULL DEFAULT 5,
    weight NUMERIC(14,2),
    dimensions VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    is_featured BOOLEAN NOT NULL DEFAULT FALSE,
    is_new_arrival BOOLEAN NOT NULL DEFAULT FALSE,
    average_rating NUMERIC(14,2) NOT NULL DEFAULT 0,
    review_count INTEGER NOT NULL DEFAULT 0,
    view_count INTEGER NOT NULL DEFAULT 0,
    sales_count INTEGER NOT NULL DEFAULT 0,
    meta_title VARCHAR(255),
    meta_description TEXT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    brand_id BIGINT,
    category_id BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(255) NOT NULL UNIQUE,
    name VARCHAR(255) NOT NULL,
    attributes TEXT,
    price NUMERIC(14,2) NOT NULL,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    reserved_quantity INTEGER NOT NULL DEFAULT 0,
    image_url VARCHAR(255),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    product_id BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS product_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_url VARCHAR(255) NOT NULL,
    thumbnail_url VARCHAR(255),
    alt_text VARCHAR(255),
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    product_id BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS product_specifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    value VARCHAR(255) NOT NULL,
    group_name VARCHAR(255),
    sort_order INTEGER NOT NULL DEFAULT 0,
    product_id BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rating INTEGER NOT NULL,
    title VARCHAR(255) NOT NULL,
    comment TEXT,
    pros TEXT,
    cons TEXT,
    images TEXT,
    is_verified_purchase BOOLEAN NOT NULL DEFAULT FALSE,
    helpful_count INTEGER NOT NULL DEFAULT 0,
    not_helpful_count INTEGER NOT NULL DEFAULT 0,
    admin_reply TEXT,
    admin_reply_at TIMESTAMP,
    status VARCHAR(40) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    product_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id VARCHAR(255) UNIQUE,
    applied_promo_code VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    user_id BIGINT UNIQUE
);
CREATE TABLE IF NOT EXISTS cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity INTEGER NOT NULL,
    price_at_add NUMERIC(14,2) NOT NULL,
    cart_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    variant_id BIGINT
);
CREATE TABLE IF NOT EXISTS wishlists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_at_add NUMERIC(14,2) NOT NULL,
    notify_on_price_drop BOOLEAN NOT NULL DEFAULT FALSE,
    notify_on_back_in_stock BOOLEAN NOT NULL DEFAULT FALSE,
    added_at TIMESTAMP NOT NULL,
    user_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS shop_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(255) NOT NULL UNIQUE,
    status VARCHAR(40) NOT NULL,
    delivery_method VARCHAR(40) NOT NULL,
    delivery_tracking_number VARCHAR(255),
    estimated_delivery_date DATE,
    actual_delivery_date DATE,
    subtotal NUMERIC(14,2) NOT NULL,
    shipping_cost NUMERIC(14,2) NOT NULL,
    discount NUMERIC(14,2) NOT NULL,
    bonus_points_used INTEGER NOT NULL DEFAULT 0,
    bonus_points_earned INTEGER NOT NULL DEFAULT 0,
    total_amount NUMERIC(14,2) NOT NULL,
    promo_code VARCHAR(255),
    customer_note TEXT,
    admin_note TEXT,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    paid_at TIMESTAMP,
    shipped_at TIMESTAMP,
    delivered_at TIMESTAMP,
    user_id BIGINT NOT NULL,
    shipping_recipient_name VARCHAR(255),
    shipping_recipient_phone VARCHAR(255),
    shipping_country VARCHAR(255),
    shipping_city VARCHAR(255),
    shipping_street VARCHAR(255),
    shipping_building VARCHAR(255),
    shipping_apartment VARCHAR(255),
    shipping_postal_code VARCHAR(255)
);
CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quantity INTEGER NOT NULL,
    price_at_purchase NUMERIC(14,2) NOT NULL,
    product_snapshot TEXT NOT NULL,
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    variant_id BIGINT
);
CREATE TABLE IF NOT EXISTS payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id VARCHAR(255) UNIQUE,
    payment_method VARCHAR(40) NOT NULL,
    status VARCHAR(40) NOT NULL,
    amount NUMERIC(14,2) NOT NULL,
    currency VARCHAR(255) NOT NULL,
    bonus_points_used INTEGER NOT NULL DEFAULT 0,
    card_last_four_digits VARCHAR(255),
    paid_at TIMESTAMP,
    error_message VARCHAR(255),
    error_code VARCHAR(255),
    refunded_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    metadata TEXT,
    order_id BIGINT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS delivery_options (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    code VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,
    base_price NUMERIC(14,2) NOT NULL,
    free_threshold NUMERIC(14,2) NOT NULL,
    estimated_days_min INTEGER NOT NULL,
    estimated_days_max INTEGER NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS promo_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(255) NOT NULL UNIQUE,
    description TEXT,
    discount_type VARCHAR(40) NOT NULL,
    discount_value NUMERIC(14,2) NOT NULL,
    min_order_amount NUMERIC(14,2) NOT NULL DEFAULT 0,
    max_discount_amount NUMERIC(14,2),
    max_usage_count INTEGER,
    current_usage_count INTEGER NOT NULL DEFAULT 0,
    max_usage_per_user INTEGER NOT NULL DEFAULT 1,
    valid_from TIMESTAMP NOT NULL,
    valid_to TIMESTAMP NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by_id BIGINT
);
CREATE TABLE IF NOT EXISTS promo_code_usages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discount_applied NUMERIC(14,2) NOT NULL,
    used_at TIMESTAMP NOT NULL,
    promo_code_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    order_id BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(255) NOT NULL UNIQUE,
    expiry_date TIMESTAMP NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL,
    user_id BIGINT NOT NULL
);
